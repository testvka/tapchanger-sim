// Writes EXPLANATIONS.md and explanations.html: the explanation of each of the 32 tap-changer configurations, with
// both cases of its pair (TCnn with load, NLnn no load). Usage: node explain_all.mjs
//
// For beginners: for each configuration row 1..32 it explains the loaded case and the no-load case, keeps the
// sections of the loaded case and adds the no-load "network" section next to the loaded one. The HTML page reuses
// the stylesheet of index.html. Side effects: overwrites EXPLANATIONS.md and explanations.html in this folder.
import { readFileSync, writeFileSync } from "node:fs";
import { defaultModel, solveWithControl } from "./solver.mjs";
import { explain, presetModel, renderHtml, renderMarkdown } from "./explain.mjs";

const presets = JSON.parse(readFileSync(new URL("./presets.json", import.meta.url)));
const rows = [...new Set(presets.map((p) => p.row))].sort((a, b) => a - b);
/** Short title of a preset: "2W: RatioTapChanger on end 1 ...". */
const short = (p) => `${p.windings}W: ` + p.title.replace(/^.*?: /, "");

/** The merged explanation of one configuration row: { tc, nl, ex }. */
function pairExplanation(row) {
  const tc = presets.find((p) => p.row === row && !p.noload);
  const nl = presets.find((p) => p.row === row && p.noload);
  // explain one preset: build its model, solve it with control, explain the result
  const ex = (p) => { const m = presetModel(p, defaultModel); return explain(m, solveWithControl(m), presets, defaultModel); };
  const a = ex(tc), b = ex(nl);
  const sections = [];
  for (const s of a.sections) {
    if (s.id === "network") {
      sections.push({ ...s, title: `${s.title} (${tc.code})` });
      const n = b.sections.find((x) => x.id === "network");
      sections.push({ ...n, title: `${n.title} (${nl.code})` });
    } else {
      sections.push(s);
    }
  }
  return { tc, nl, ex: { ...a, sections } };
}

const all = rows.map(pairExplanation);
/** Anchor id of a row in the documents: 8 -> "c08". */
const anchor = (row) => `c${String(row).padStart(2, "0")}`;
const intro = "Each of the 32 configurations is one combination of tap changers on a two- or three-winding transformer. "
  + "It comes as a pair: the loaded case TCnn (TX in parallel with a plain transformer TP, feeding a load) and the no-load "
  + "case NLnn (TX alone, the other ends open), with the same tap changers at the same steps. "
  + "The simulator shows the same explanation live for whatever combination is set up.";

// ---------------------------------------------------------------- Markdown
let md = `# Tap changer combinations explained\n\n${intro} Generated by \`node explain_all.mjs\`; do not edit by hand.\n\n`;
md += "| # | Combination | With load | No load |\n|---|---|---|---|\n"
  + all.map(({ tc, nl }) => `| [${tc.row}](#${anchor(tc.row)}) | ${short(tc)} | ${tc.code} | ${nl.code} |`).join("\n") + "\n\n";
for (const { tc, ex } of all) {
  md += `<a id="${anchor(tc.row)}"></a>\n\n## ${tc.row}. ${tc.title}\n\n` + renderMarkdown(ex, 3);
}
writeFileSync(new URL("./EXPLANATIONS.md", import.meta.url), md.replace(/\n{3,}/g, "\n\n"));

// ---------------------------------------------------------------- HTML
const css = readFileSync(new URL("./index.html", import.meta.url), "utf8").match(/<style>([\s\S]*?)<\/style>/)[1];
/** Escape text for HTML (&, <, >). */
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Tap changer combinations explained</title>
<style>${css}
.toc{columns:2 320px;padding-left:1.2em;font-size:.9rem} .case{border-top:1px solid #ddd;padding-top:12px;margin-top:22px} .case h2{font-size:1.15rem}
</style></head><body>
<!-- generated by explain_all.mjs from explain.mjs + presets.json; edit those, not this -->
<div class="wrap">
  <header><h1>Tap changer combinations explained</h1><p>${esc(intro)} <a href="index.html">Open the simulator</a></p></header>
  <ol class="toc">${all.map(({ tc }) => `<li><a href="#${anchor(tc.row)}">${esc(short(tc))}</a></li>`).join("")}</ol>
  ${all.map(({ tc, ex }) => `<section class="case explain" id="${anchor(tc.row)}"><h2>${tc.row}. ${esc(tc.title)}</h2>${renderHtml(ex, { links: true })}</section>`).join("\n  ")}
</div>
</body></html>
`;
writeFileSync(new URL("./explanations.html", import.meta.url), html);
console.log(`wrote EXPLANATIONS.md (${(md.length / 1024).toFixed(0)} kB) and explanations.html (${(html.length / 1024).toFixed(0)} kB) for ${all.length} configurations`);
